// Package pfproxy — HTTP port-forward для веб-режима (ADR-0017).
//
// Браузер открывает поток по адресу https://{id}.pf.<base-domain>/: у каждого потока свой origin, поэтому
// проксируемое приложение не получает ни cookie сессии Kubron, ни его CSRF-токен. Доступ выдаётся одноразовым
// подписанным ticket'ом со сроком в секунды, который меняется на cookie, действующую только на хосте потока.
//
// Пакет не открывает портов на хосте сервера: на каждое соединение прокси вызывает Target.Dial, а тот
// строит поток к поду (SPDY к kube-apiserver). Пакет зависит только от стандартной библиотеки, поэтому
// internal/k8s может его импортировать.
package pfproxy
