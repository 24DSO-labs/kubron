// Package ext — публичные точки расширения Kubron (ADR-0011, ADR-0013).
//
// Код в internal/ другой Go-модуль импортировать не может, поэтому всё, что должны
// реализовывать внешние модули (платный SSO/OIDC, серверное хранилище на PostgreSQL,
// оболочки), описано здесь и не зависит от internal/. Ядро принимает эти интерфейсы
// и адаптирует их к своим внутренним типам.
//
// Статус API: НЕСТАБИЛЬНЫЙ до этапа 6 (SSO). До этого момента интерфейсы могут меняться;
// число в APIVersion растёт при несовместимом изменении, а Registry.Install отказывается
// подключать модуль, собранный под другую версию.
//
// Пакет использует только стандартную библиотеку.
package ext

